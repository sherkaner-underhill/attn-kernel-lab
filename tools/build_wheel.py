"""Build the packaged (fat) wheel of the fused prefill attention extension.

The manifest's one named gap: v0.3.0 had no wheel, so its ``artifacts`` block
had to record the JIT source build as the artifact and name the packaging hole
in ``limitations``. This tool closes it. What it produces is a wheel that can
answer, from its own metadata and with no repository present, the questions a
promotion record asks of a binary: which sources went in, which architectures
came out, and which toolchain built it.

Three properties are load-bearing.

**Both architectures, and never a bare ``-arch``.** The wheel carries SASS for
every registered mma.sync target -- ``sm_89`` (development tier) and
``sm_120a`` (production tier) -- generated by ``kernel.gencode_for``, the one
place in the repository that knows about claim K5: a bare ``-arch=sm_120a``
executable build silently lowers to ``sm_120`` and ptxas then rejects the
architecture-specific MMA. The flags are *derived* from each target profile's
declared compute capability and then cross-checked against the ``toolchain
.gencode`` string that profile publishes, so a profile that ever grows a bare
``-arch`` fails this build instead of shipping a wheel that cannot run.

**One Python surface.** The wheel installs a separate top-level distribution,
``attn_kernel_lab_ext``, holding the compiled module and its build info -- not a
second copy of ``attn_kernel_lab``. A wheel that shipped both would put two
copies of the loader and the contract validation on ``sys.path``, and whichever
won the import race would decide which one actually ran.

**A real, recomputable build id.** ``build_id`` is ``kernel.source_build_id()``
-- sha256 over the same canonical source set, in the same order, with the same
semantics as the JIT path reports -- so a wheel built from a given tree and that
tree's own source digest are directly comparable. The per-file digests ride
along so a mismatch can say *which* file moved.

    tools/build_wheel.py                                 # dev build -> dist/
    tools/build_wheel.py --release-id d256-int8-fp8-v0.4.0
    tools/build_wheel.py --outdir /tmp/wheels --json /tmp/wheels/build.json

Needs torch importable at build time (so ``pip`` runs with
``--no-build-isolation``) and ``nvcc`` on ``PATH``.
"""
