#: other, and the failure surfaces as a driver-level "no kernel image" long
#: after the build that caused it.
DEFAULT_TARGETS = ("sm89-rtx4090-local", "sm120-rtxpro6000-server")

#: Digest paths of the manifest's ``source.source_tree_sha256`` (v0.3.0 record).
DIGEST_PATHS = ("src", "tests/kernel")

