def resolve_targets(target_ids) -> list[dict]:
    """Derive the code-generation targets from the registered target profiles.

    Each profile's ``device.compute_capability`` generates the flag through
    ``kernel.gencode_for``; the profile's own ``toolchain.gencode`` string then
    has to agree. That cross-check is the point: it makes a registry that ever
    records a bare ``-arch`` (claim K5) fail the build rather than produce a
    wheel whose SASS silently lowered.
    """
    targets = []
    for target_id in target_ids:
        profile_path = ROOT / "targets" / f"{target_id}.yaml"
        if not profile_path.exists():
            raise SystemExit(f"no such target profile: {profile_path}")
        profile = yaml.safe_load(profile_path.read_text(encoding="utf-8"))
        major, minor = (int(value) for value in profile["device"]["compute_capability"])
        gencode = kernel_mod.gencode_for(major, minor)
        declared = (profile.get("toolchain") or {}).get("gencode")
        if declared and declared.strip() != gencode:
            raise SystemExit(
                f"target {target_id} declares gencode {declared!r} but its compute "
                f"capability ({major}, {minor}) generates {gencode!r}. Reconcile the "
                "profile; a bare -arch form here is claim K5 and must never ship."
            )
        targets.append(
            {
                "target": target_id,
                "capability": [major, minor],
                "arch": kernel_mod.arch_tag_for(major, minor),
                "gencode": gencode,
                "family": (profile.get("capabilities") or {}).get("implementation_family"),
            }
        )
    families = {target["family"] for target in targets}
    if families - {"mma_sync"}:
        raise SystemExit(
            f"targets span implementation families {sorted(families)}; this wheel "
            "builds the mma.sync source only (a wgmma implementation is a different "
            "artifact with its own layout_version)"
        )
    return targets


def refuse_polluted_tree() -> None:
    """Stop if an in-tree build artifact would corrupt ``source_tree_sha256``.

    Found the hard way during this tool's own verification: ``pip install .``
    leaves ``src/attn_kernel_lab.egg-info/`` behind, and ``tree_digest.py`` --
    the ONLY sanctioned producer of that field -- has no exclusion for it, so
    the digest silently stops matching a clean checkout of the same commit.
    Embedding one of those into a wheel would produce an artifact whose pin no
    reviewer could reproduce, which is worse than a failed build.
    """
    strays = sorted(
        stray
        for path in DIGEST_PATHS
        for pattern in ("*.egg-info", "*.dist-info")
        for stray in (ROOT / path).rglob(pattern)
    )
    if strays:
        listing = "\n  ".join(str(stray.relative_to(ROOT)) for stray in strays)
        raise SystemExit(
            "in-tree build artifacts would change source_tree_sha256:\n  "
            f"{listing}\nRemove them and rebuild (they are ignored by git, not "
            "by tree_digest.py)."
        )


def _git(*args: str) -> str | None:
    try:
        result = subprocess.run(
            ["git", "-C", str(ROOT), *args],
            capture_output=True, text=True, check=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return None
    return result.stdout.strip()


def _toolchain() -> dict:
    """Toolchain facts read from the build environment, never declared."""
    import torch

    from torch.utils.cpp_extension import CUDA_HOME

    if CUDA_HOME is None:
        raise SystemExit(
            "torch cannot find a CUDA toolkit (CUDA_HOME is unset and nvcc is not "
            "on PATH). Activate the lab environment before building."
        )
    nvcc = shutil.which("nvcc") or str(pathlib.Path(CUDA_HOME) / "bin" / "nvcc")
    version = subprocess.run(
        [nvcc, "--version"], capture_output=True, text=True, check=True
    ).stdout
    release = re.search(r"release ([\d.]+), V([\d.]+)", version)
    build = re.search(r"Build (\S+)", version)
    # CUDA_HOME itself is deliberately NOT recorded below: it is a path on the
    # build host, it says nothing the nvcc version string does not, and
    # BUILD_INFO ships inside the wheel.
    return {
        "cuda": torch.version.cuda,
        "nvcc": (
            f"nvcc {release.group(2)} ({build.group(1)})"
            if release and build
            else version.strip().splitlines()[-1]
        ),
        "torch": torch.__version__,
        "cxx11_abi": bool(torch._C._GLIBCXX_USE_CXX11_ABI),
    }


def _abi_tags(toolchain: dict) -> tuple[str, str]:
    """``(binary_abi, glibc_tag)`` for the interpreter and libc doing the build."""
    import platform

    python_tag = f"cp{sys.version_info.major}{sys.version_info.minor}"
    torch_version = toolchain["torch"].split("+")[0]
    cuda_tag = f"cu{(toolchain['cuda'] or '').replace('.', '')}"
    libc, libc_version = platform.libc_ver()
    return (
        f"{python_tag}-torch{torch_version}-{cuda_tag}",
        f"{libc or 'libc'}{libc_version}",
    )


def build_info(targets: list[dict], *, release_id: str, version: str,
               api_version: int) -> dict:
    """Everything the installed wheel will be able to say about itself.

    No timestamp, deliberately: a build time makes two builds of one tree differ
    byte-for-byte, and the whole point of ``build_id`` is that they should not.
    """
    refuse_polluted_tree()
    toolchain = _toolchain()
    binary_abi, glibc = _abi_tags(toolchain)
    arch_tags = [target["arch"] for target in targets]
    # "sm_120a" -> "sm120a" inside the variant id: the v0.3.0 record's
    # "jit-src-sm120a" spelling, kept so the two are read side by side.
    variant_tags = [arch.replace("_", "") for arch in arch_tags]
    source_sha, _ = tree_digest(ROOT, list(DIGEST_PATHS))
    commit = _git("rev-parse", "HEAD")
    status = _git("status", "--porcelain")
    return {
        "artifact_variant_id": "-".join([binary_abi, glibc, *variant_tags]),
        "binary_abi": binary_abi,
        "build_id": kernel_mod.source_build_id(),
        "candidate_commit": commit,
        "cuda_arch_targets": arch_tags,
        "digest_paths": list(DIGEST_PATHS),
        "dirty": bool(status) if status is not None else None,
        "distribution": DISTRIBUTION,
        "gencode_flags": [target["gencode"] for target in targets],
        "layout_version": V1_CAPABILITY.layout_version,
        "operator_contract_version": V1_CAPABILITY.operator_contract_version,
        "package_api_version": api_version,
        "release_id": release_id,
        "returns_lse": V1_CAPABILITY.returns_lse,
        "source_files": kernel_mod.source_file_digests(),
        "source_tree_sha256": source_sha,
        "targets": [
            {"target": target["target"], "capability": target["capability"]}
            for target in targets
        ],
        "toolchain": toolchain,
        "version": version,
    }


