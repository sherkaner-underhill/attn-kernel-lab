def stage(directory: pathlib.Path, info: dict, targets: list[dict]) -> None:
    """Write the throwaway source distribution the wheel is built from."""
    package_dir = directory / PACKAGE
    package_dir.mkdir(parents=True)
    (package_dir / "__init__.py").write_text(
        INIT_PY.replace("{ext_module}", EXT_MODULE), encoding="utf-8"
    )
    (package_dir / "_build_info.py").write_text(
        BUILD_INFO_PY.format(info=pprint.pformat(info, sort_dicts=True, width=84)),
        encoding="utf-8",
    )
    (directory / "csrc").mkdir()
    shutil.copy2(
        ROOT / "src" / "attn_kernel_lab" / "csrc" / "fp8_prefill_attn.cu",
        directory / "csrc" / "fp8_prefill_attn.cu",
    )
    (directory / "setup.py").write_text(
        SETUP_PY.format(
            nvcc_flags=pprint.pformat(["-O3", *(t["gencode"] for t in targets)]),
            distribution=DISTRIBUTION,
            version=info["version"],
            package=PACKAGE,
            ext_module=EXT_MODULE,
        ),
        encoding="utf-8",
    )
    (directory / "pyproject.toml").write_text(PYPROJECT_TOML, encoding="utf-8")


def run_pip_wheel(source: pathlib.Path, outdir: pathlib.Path, verbose: bool) -> pathlib.Path:
    """Build into a private directory, then publish the one wheel it produced.

    Building straight into ``outdir`` would make "which file did this run
    produce?" a question about directory contents, and a rebuild that lands on
    an existing filename would be indistinguishable from having produced
    nothing.
    """
    outdir.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="attn-kernel-lab-whl-") as staging:
        command = [
            sys.executable, "-m", "pip", "wheel",
            "--no-build-isolation", "--no-deps",
            "--wheel-dir", staging, str(source),
        ]
        print(f"$ {' '.join(command)}", flush=True)
        result = subprocess.run(
            command, text=True,
            stdout=None if verbose else subprocess.PIPE,
            stderr=subprocess.STDOUT if not verbose else None,
        )
        if result.returncode != 0:
            if result.stdout:
                print(result.stdout)
            raise SystemExit(f"pip wheel failed with exit code {result.returncode}")
        produced = sorted(pathlib.Path(staging).glob("*.whl"))
        if len(produced) != 1:
            raise SystemExit(f"expected exactly one wheel, got {produced}")
        return pathlib.Path(shutil.copy2(produced[0], outdir / produced[0].name))


def verify_arches(wheel: pathlib.Path, expected: list[str]) -> list[str]:
    """cuobjdump the wheel's compiled module; require every expected arch.

    The build-time half of claim K5. A wheel whose SASS silently lowered is
    indistinguishable from a correct one until it reaches a device that cannot
    run it, so the check belongs here, before anyone installs it.
    """
    cuobjdump = shutil.which("cuobjdump")
    if cuobjdump is None:
        print("WARNING: cuobjdump not on PATH; architecture verification SKIPPED")
        return []
    with tempfile.TemporaryDirectory() as tmp:
        with zipfile.ZipFile(wheel) as archive:
            names = [name for name in archive.namelist() if name.endswith(".so")]
            if len(names) != 1:
                raise SystemExit(f"expected exactly one .so in {wheel.name}, got {names}")
            extracted = pathlib.Path(archive.extract(names[0], tmp))
        listing = subprocess.run(
            [cuobjdump, "--list-elf", str(extracted)],
            capture_output=True, text=True, check=True,
        ).stdout
    lines = [line.strip() for line in listing.splitlines() if line.strip()]
    missing = [arch for arch in expected if not any(f".{arch}." in line for line in lines)]
    if missing:
        raise SystemExit(
            f"{wheel.name} carries no code for {missing}; cuobjdump --list-elf said:\n"
            + "\n".join(lines)
        )
    return lines


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--outdir", type=pathlib.Path, default=ROOT / "dist",
                        help="where to leave the wheel (default: dist/)")
    parser.add_argument("--target", action="append", dest="targets", default=None,
                        metavar="TARGET_ID",
                        help=f"registered target to build for; repeatable "
                             f"(default: {' '.join(DEFAULT_TARGETS)})")
    parser.add_argument("--release-id", default=UNRELEASED,
                        help="release this artifact belongs to; stays 'unreleased' "
                             "until a qualified release exists, so a pin check fails "
                             "closed against a development build")
    parser.add_argument("--version", default=None,
                        help=f"wheel version (default: derived from --release-id, "
                             f"else {DEV_VERSION})")
    parser.add_argument("--package-api-version", type=int, default=None,
                        help="override the derived package_api_version (contract §2)")
    parser.add_argument("--json", type=pathlib.Path, default=None,
                        help="also write the build summary here as JSON")
    parser.add_argument("--keep-build", action="store_true",
                        help="leave the staged build tree in place for inspection")
    parser.add_argument("--no-verify", action="store_true",
                        help="skip the cuobjdump architecture check (not recommended)")
    parser.add_argument("-v", "--verbose", action="store_true")
    args = parser.parse_args(argv)

    targets = resolve_targets(args.targets or DEFAULT_TARGETS)
    release_match = re.search(r"v(\d+\.\d+\.\d+)$", args.release_id)
    version = args.version or (release_match.group(1) if release_match else DEV_VERSION)
    api_version = (
        args.package_api_version
        if args.package_api_version is not None
        else package_api_version()
    )

    info = build_info(
        targets, release_id=args.release_id, version=version, api_version=api_version
    )
    print(f"distribution : {DISTRIBUTION} {version}")
    print(f"release_id   : {info['release_id']}")
    print(f"variant      : {info['artifact_variant_id']}")
    print(f"build_id     : {info['build_id']}")
    print(f"source tree  : {info['source_tree_sha256']} over {list(DIGEST_PATHS)}")
    print(f"gencode      : {' '.join(info['gencode_flags'])}")
    print(f"toolchain    : {info['toolchain']['nvcc']}, torch {info['toolchain']['torch']}")

    build_root = pathlib.Path(tempfile.mkdtemp(prefix="attn-kernel-lab-wheel-"))
    try:
        stage(build_root, info, targets)
        wheel = run_pip_wheel(build_root, args.outdir.resolve(), args.verbose)
    finally:
        if args.keep_build:
            print(f"build tree   : {build_root}")
        else:
            shutil.rmtree(build_root, ignore_errors=True)

    evidence = [] if args.no_verify else verify_arches(wheel, info["cuda_arch_targets"])
    summary = {
        "wheel": str(wheel),
        "wheel_sha256": hashlib.sha256(wheel.read_bytes()).hexdigest(),
        "build_info": info,
        "cuobjdump_list_elf": evidence,
    }
    print(f"\nwheel        : {wheel}")
    print(f"wheel_sha256 : {summary['wheel_sha256']}")
    for line in evidence:
        print(f"  cuobjdump  : {line}")
    if args.json:
        args.json.write_text(json.dumps(summary, indent=2, sort_keys=True) + "\n",
                             encoding="utf-8")
        print(f"summary      : {args.json}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
